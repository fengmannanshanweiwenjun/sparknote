export const Sidebar = {
  name: 'Sidebar',
  setup() {
    const ui = useUiStore();
    const content = useContentStore();
    const navItems = [
      { key: 'dashboard', icon: 'home', label: '工作台' },
      { key: 'editor', icon: 'edit', label: '创作' },
      { key: 'library', icon: 'library', label: '内容库' },
      { key: 'calendar', icon: 'calendar', label: '日历' },
    ];
    function navigate(key) { ui.navigate(key); }
    function newPost() {
      content.newDraft();
      ui.navigate('editor');
    }
    return { ui, navItems, navigate, newPost, icons };
  },
  template: `
    <aside class="sidebar" :class="{ expanded: ui.sidebarExpanded }">
      <div class="sidebar-logo" @click="ui.toggleSidebar()" title="星火笔记">火</div>
      <nav class="sidebar-nav">
        <div v-for="item in navItems" :key="item.key"
             class="sidebar-item" :class="{ active: ui.currentRoute === item.key }"
             @click="navigate(item.key)">
          <span v-html="icons[item.icon]"></span>
          <span class="label">{{ item.label }}</span>
        </div>
      </nav>
      <div class="sidebar-bottom">
        <div class="sidebar-item" @click="newPost">
          <span v-html="icons.plus"></span>
          <span class="label">新建</span>
        </div>
        <div class="sidebar-item" @click="navigate('settings')">
          <span v-html="icons.settings"></span>
          <span class="label">设置</span>
        </div>
      </div>
    </aside>
  `
};

const routeNames = {
  dashboard: '工作台', editor: '创作编辑器', library: '内容库',
  calendar: '内容日历', settings: '设置'
};

export const Topbar = {
  name: 'Topbar',
  setup() {
    const ui = useUiStore();
    const content = useContentStore();
    return { ui, content, routeNames, icons };
  },
  template: `
    <header class="topbar">
      <div class="topbar-left">
        <h1 class="topbar-title">{{ routeNames[ui.currentRoute] || '' }}</h1>
      </div>
      <div class="topbar-right">
        <div v-if="ui.currentRoute === 'library'" class="library-search">
          <span v-html="icons.search"></span>
          <input v-model="content.searchQuery" placeholder="搜索内容..." />
        </div>
        <button class="btn btn-primary" @click="content.newDraft(); ui.navigate('editor')">
          <span v-html="icons.plus"></span> 新建笔记
        </button>
      </div>
    </header>
  `
};
